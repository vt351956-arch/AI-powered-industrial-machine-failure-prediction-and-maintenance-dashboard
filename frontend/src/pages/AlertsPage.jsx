import { useState, useEffect } from 'react';
import { useNavigate } from 'react-router-dom';
import { PageLoader, ErrorState, EmptyState, Card, Button, Input, Select } from '../components/ui/UIComponents';
import { AlertTriangle, Search, RefreshCw, Eye, Filter } from 'lucide-react';
import { alertService, machineService } from '../services/api';

export default function AlertsPage() {
  const navigate = useNavigate();
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [alerts, setAlerts] = useState([]);
  const [machines, setMachines] = useState([]);
  const [severityFilter, setSeverityFilter] = useState('');
  const [machineFilter, setMachineFilter] = useState('');

  useEffect(() => {
    loadData();
  }, [severityFilter, machineFilter]);

  const loadData = async () => {
    setLoading(true);
    setError(null);
    try {
      const [alertsRes, machinesRes] = await Promise.all([
        alertService.list({
          severity: severityFilter || undefined,
          machine_id: machineFilter || undefined,
        }).catch(err => {
          console.error('Alerts API error:', err);
          return { data: [] };
        }),
        machineService.list({ limit: 100 }).catch(err => {
          console.error('Machines API error:', err);
          return { data: [] };
        }),
      ]);

      setAlerts(alertsRes.data || []);
      setMachines(machinesRes.data || []);
    } catch (err) {
      console.error('Failed to load alerts:', err);
      setError('Failed to load alerts. Please check your connection.');
    } finally {
      setLoading(false);
    }
  };

  const getSeverityColor = (severity) => {
    switch (severity?.toUpperCase()) {
      case 'CRITICAL': return 'text-rose-400 bg-rose-500/10 border-rose-500/30';
      case 'WARNING': return 'text-amber-400 bg-amber-500/10 border-amber-500/30';
      case 'INFO': return 'text-cyan-400 bg-cyan-500/10 border-cyan-500/30';
      default: return 'text-slate-400 bg-slate-500/10 border-slate-500/30';
    }
  };

  const getAlertTypeLabel = (type) => {
    switch (type) {
      case 'HIGH_RISK': return 'High Risk';
      case 'MEDIUM_RISK': return 'Medium Risk';
      case 'SENSOR_ANOMALY': return 'Sensor Anomaly';
      case 'CRITICAL_STATUS': return 'Critical Status';
      default: return type;
    }
  };

  // Calculate summary
  const totalAlerts = alerts.length;
  const criticalAlerts = alerts.filter(a => a.severity === 'CRITICAL').length;
  const warningAlerts = alerts.filter(a => a.severity === 'WARNING').length;

  if (loading) {
    return (
      <div className="p-6">
        <PageLoader message="Loading alerts..." />
      </div>
    );
  }

  if (error) {
    return (
      <div className="p-6">
        <ErrorState message={error} onRetry={loadData} />
      </div>
    );
  }

  return (
    <div className="p-6 space-y-6">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-2xl font-bold text-white">System Alerts</h1>
          <p className="text-slate-400 text-sm mt-1">
            Monitor machine-related alerts generated by the predictive maintenance system
          </p>
        </div>
        <Button variant="secondary" onClick={loadData} icon={RefreshCw}>
          Refresh
        </Button>
      </div>

      {/* Summary Cards */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
        <Card>
          <div className="flex items-center gap-4">
            <div className="w-12 h-12 rounded-xl bg-brand-500/10 flex items-center justify-center">
              <AlertTriangle className="w-6 h-6 text-brand-400" />
            </div>
            <div>
              <p className="text-slate-400 text-sm">Total Alerts</p>
              <p className="text-2xl font-bold text-white">{totalAlerts}</p>
            </div>
          </div>
        </Card>
        <Card>
          <div className="flex items-center gap-4">
            <div className="w-12 h-12 rounded-xl bg-rose-500/10 flex items-center justify-center">
              <AlertTriangle className="w-6 h-6 text-rose-400" />
            </div>
            <div>
              <p className="text-slate-400 text-sm">Critical</p>
              <p className="text-2xl font-bold text-white">{criticalAlerts}</p>
            </div>
          </div>
        </Card>
        <Card>
          <div className="flex items-center gap-4">
            <div className="w-12 h-12 rounded-xl bg-amber-500/10 flex items-center justify-center">
              <AlertTriangle className="w-6 h-6 text-amber-400" />
            </div>
            <div>
              <p className="text-slate-400 text-sm">Warning</p>
              <p className="text-2xl font-bold text-white">{warningAlerts}</p>
            </div>
          </div>
        </Card>
      </div>

      {/* Filters */}
      <Card>
        <div className="flex flex-col lg:flex-row gap-4">
          <div className="flex-1">
            <Select
              value={severityFilter}
              onChange={(e) => setSeverityFilter(e.target.value)}
            >
              <option value="">All Severities</option>
              <option value="CRITICAL">Critical</option>
              <option value="WARNING">Warning</option>
              <option value="INFO">Info</option>
            </Select>
          </div>
          <div className="flex-1">
            <Select
              value={machineFilter}
              onChange={(e) => setMachineFilter(e.target.value)}
            >
              <option value="">All Machines</option>
              {machines.map(machine => (
                <option key={machine.id} value={machine.id}>
                  {machine.machine_code} - {machine.machine_name}
                </option>
              ))}
            </Select>
          </div>
        </div>
      </Card>

      {/* Alerts List */}
      {alerts.length === 0 ? (
        <EmptyState
          icon={AlertTriangle}
          title="No Alerts Found"
          description={severityFilter || machineFilter ? "Try adjusting your filters." : "No active alerts in the system."}
        />
      ) : (
        <div className="space-y-3">
          {alerts.map((alert) => (
            <Card key={alert.id}>
              <div className="flex items-start gap-4">
                <div className="w-10 h-10 rounded-full flex items-center justify-center shrink-0 mt-1">
                  <AlertTriangle className={`w-5 h-5 ${
                    alert.severity === 'CRITICAL' ? 'text-rose-400' :
                    alert.severity === 'WARNING' ? 'text-amber-400' :
                    'text-cyan-400'
                  }`} />
                </div>
                <div className="flex-1 min-w-0">
                  <div className="flex items-center gap-2 mb-2 flex-wrap">
                    <span className={`text-xs font-semibold px-2 py-0.5 rounded border ${getSeverityColor(alert.severity)}`}>
                      {alert.severity}
                    </span>
                    <span className="text-slate-500 text-xs">
                      {getAlertTypeLabel(alert.alert_type)}
                    </span>
                    <span className="text-slate-500 text-xs">
                      {new Date(alert.timestamp).toLocaleString()}
                    </span>
                  </div>
                  <p className="text-white font-medium mb-1">{alert.title}</p>
                  <p className="text-slate-400 text-sm mb-2">{alert.message}</p>
                  <div className="flex items-center gap-4">
                    <p className="text-slate-500 text-xs">
                      <span className="text-slate-400">Machine:</span> {alert.machine_code} - {alert.machine_name}
                    </p>
                    {alert.metric_value !== null && (
                      <p className="text-slate-500 text-xs">
                        <span className="text-slate-400">Value:</span> {alert.metric_value.toFixed(2)} {alert.metric_unit}
                      </p>
                    )}
                  </div>
                </div>
                <Button
                  variant="ghost"
                  size="sm"
                  onClick={() => navigate(`/machines/${alert.machine_id}`)}
                  icon={Eye}
                >
                  View Machine
                </Button>
              </div>
            </Card>
          ))}
        </div>
      )}
    </div>
  );
}
